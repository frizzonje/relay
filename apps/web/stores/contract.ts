import { create } from 'zustand';

/**
 * Клиент и сервер говорят на разных версиях контракта.
 *
 * Флаг, а не тост, по той же причине, что и бан: сокета после такого отказа
 * нет вовсе, и приложение вокруг — рейка, каналы, композер — остаётся
 * декорацией, которая молча ничего не делает. До 1.0 версии не было, и
 * отставший клиент выглядел не устаревшим, а сломанным.
 *
 * Сторона важна: `client` чинится перезагрузкой (вкладка держит бандл, скачанный
 * до обновления сервера) или обновлением приложения, `server` не чинится
 * человеком вовсе — там relay старее, чем его клиент, и это забота хозяина
 * машины. Совет не той стороне хуже отсутствия совета.
 */
export type Outdated = 'client' | 'server';

interface ContractState {
  outdated: Outdated | null;
  setOutdated: (side: Outdated) => void;
  /**
   * Инсталляция закрыта на обслуживание. Строка — то, что написал владелец
   * (`maintenance.message`); пустая означает «закрыто, а объяснения не
   * оставили», и экран скажет об этом своими словами.
   *
   * Едет она вместе с отказом двери, а не снимком настроек: снимок приходит по
   * сокету, которого у отвергнутого как раз и нет.
   */
  maintenance: string | null;
  setMaintenance: (text: string) => void;
  /**
   * Адрес, с которого стучится эта вкладка, закрыт владельцем.
   *
   * Флаг, а не текст: объяснять здесь нечего и незачем. За одним адресом сидит
   * подъезд, институт, оператор — попавший под маску мог не делать ничего, и
   * подробности о чужом конфликте ему не помогут, а обвинить его они успеют.
   */
  blocked: boolean;
  setBlocked: (blocked: boolean) => void;
}

export const useContractStore = create<ContractState>((set) => ({
  outdated: null,
  setOutdated: (side) => set({ outdated: side }),
  maintenance: null,
  setMaintenance: (text) => set({ maintenance: text }),
  blocked: false,
  setBlocked: (blocked) => set({ blocked }),
}));
