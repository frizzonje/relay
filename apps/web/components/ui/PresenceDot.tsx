import { useT } from '@/lib/i18n';
import { cn } from '@/lib/utils';
import { PRESENCE_LABEL_KEY } from '@/stores/presence';
import type { PresenceState } from '@relay/shared';

/**
 * Точка присутствия — единственная во всём вебе. Раньше в двух местах
 * (`Members`, `OnlineMembers`) жил один и тот же кусок разметки, вписанный
 * псевдоэлементом и намертво зелёный — фактически заглушка на одно состояние
 * «в эфире». Здесь та же точка, но настоящая: она умеет все четыре состояния
 * присутствия, и умеет их ровно в одном месте — второй копии этой разметки в
 * коде быть не должно. Появись она, два места неизбежно разъедутся в цвете, и
 * это заметят не сразу, а на первой жалобе «а почему тут точка другая».
 *
 * Соответствие цвета состоянию — по ограничению плана 2.0: зелёный `ok`
 * закреплён за «дозвон возможен» (тем самым — только за `online`, потому что
 * дозвониться тому, кто уже в другом разговоре или недавно вышел, не то же
 * самое, что дозвониться тому, кто сейчас на связи), а красный `danger` —
 * только за исходом звонка (отбой/отклонён/пропущен, задача 3+). Ни один, ни
 * другой не годятся декоративно ни для одного из оставшихся трёх состояний:
 *
 *  • `in-voice` — `warn` (янтарный): человек на связи, но занят разговором —
 *    ближе по смыслу к «подожди», чем к «звони».
 *  • `recent` — сплошная, но приглушённая заливка (`text-dim`): был здесь
 *    только что, ещё не то же самое, что «сейчас на связи», но и не пустота.
 *  • `offline` — обводка без заливки: состояние существует (личность заведена
 *    в инсталляции), но заявлять о ней нечего, а «ничего не заявлять» и есть
 *    точка, которая не кричит.
 *
 * Цвет — не единственный носитель смысла: `title`/`aria-label` называют
 * состояние словом, так что человек без цветового зрения и скринридер узнают
 * его тем же путём, что и глаз.
 */
const APPEARANCE: Record<PresenceState, string> = {
  online: 'bg-ok',
  'in-voice': 'bg-warn',
  recent: 'bg-text-dim',
  offline: 'border border-line-strong bg-transparent',
};

export function PresenceDot({
  state,
  size = 10,
  className,
}: {
  state: PresenceState;
  /** Сторона в пикселях. */
  size?: number;
  /**
   * Позиционирование и разделительное кольцо с фоном — дело вызывающего: сам
   * фон под точкой разный (сайдбар, рейка, карточка), и одного кольца на все
   * места нет (см. как `Members`/`OnlineMembers` подбирали `ring-bg-sidebar`
   * под свою панель).
   */
  className?: string;
}) {
  const t = useT();
  const label = t(PRESENCE_LABEL_KEY[state]);
  return (
    <span
      role="img"
      aria-label={label}
      title={label}
      className={cn('inline-block shrink-0 rounded-full', APPEARANCE[state], className)}
      style={{ width: size, height: size }}
    />
  );
}
