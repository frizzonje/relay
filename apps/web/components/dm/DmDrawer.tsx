'use client';

import { useEffect, useRef, useState } from 'react';
import { DmList } from '@/components/dm/DmList';
import { DM_ENTRY_ID } from '@/components/layout/Toolbar';
import { useUiStore } from '@/stores/ui';

/**
 * Док личных сообщений на десктопе: колонка между составом и рейкой тулбара.
 *
 * Два состояния и никакой середины. Раскрытый — 232px, ровно как колонка
 * состава рядом. Свёрнутый — НИЧЕГО: ни полоски, ни язычка, ни следа. Раскладка
 * возвращается ровно к той, что была до личных сообщений, — состав вплотную к
 * рейке. В этом весь смысл сворачивания: раздел, которым сейчас не пользуются,
 * не должен отнимать ни точки экрана и ни грамма внимания.
 *
 * Свёрнутым доку нечего показывать — значит, и нечем управлять: своей кнопки у
 * него нет. Раздел ЛС раскрывает цель в рейке (`Toolbar`) — та самая, что
 * подсвечена, пока раздел открыт, и носит на себе счёт непрочитанного. Второй
 * орган на 14 точках рядом с ней был бы не «удобнее», а просто вторым.
 *
 * Колонка, а не всплывшая поверх панель: пока док накладывался, раскрыть список
 * значило стереть с экрана всё, что стояло справа, — в канале состав, в беседе
 * карточку собеседника с кнопкой звонка. Место дока забирает сцена,
 * единственная тянущаяся часть раскладки.
 *
 * Ширину ведёт CSS-переход, а не пружина Framer: ширина колонки — это
 * раскладка, её каждый кадр пересчитывает весь ряд, и застрявшая на полпути
 * пружина (вкладка в фоне, кадры не идут) оставила бы раскладку в
 * недосчитанном состоянии. У CSS-перехода конечное значение стоит в стиле
 * сразу, чем бы ни кончилась анимация.
 */

/** Раскрытая ширина — та же, что у колонки состава: это одна и та же полоса. */
export const DM_DOCK_WIDTH = 232;

/**
 * Сколько едет створка. Одно число на две вещи разом — на длительность перехода
 * и на то, когда снимать панель с разметки, — потому что разъехаться им нельзя:
 * снять раньше значит показать пустой проём, позже — держать на странице то,
 * чего на экране уже нет.
 */
const SLIDE_MS = 240;

export function DmDrawer() {
  const open = useUiStore((s) => s.dmSection);
  const dock = useRef<HTMLDivElement>(null);
  /**
   * Панель переживает свой уход: пока док съезжает, ей ещё есть что показывать.
   * Без этого список пропадал бы мгновенно, а следом ещё четверть секунды
   * закрывался пустой проём — и вместо «уехала» получалось «моргнула».
   */
  const [mounted, setMounted] = useState(open);

  useEffect(() => {
    if (open) {
      setMounted(true);
      return;
    }

    // Фокус мог остаться внутри уезжающей панели — на кнопке «свернуть», к
    // примеру, которая её и свернула. Через мгновение этот узел со страницы
    // снимут, фокус свалится на body, и следующий Tab начнёт обход с начала
    // страницы. Возвращаем его туда, где раздел ЛС теперь и живёт целиком.
    if (dock.current?.contains(document.activeElement)) {
      document.getElementById(DM_ENTRY_ID)?.focus();
    }

    const id = setTimeout(() => setMounted(false), SLIDE_MS);
    return () => clearTimeout(id);
  }, [open]);

  return (
    <div
      ref={dock}
      data-testid="dm-dock"
      data-open={open || undefined}
      style={{ width: open ? DM_DOCK_WIDTH : 0, transitionDuration: `${SLIDE_MS}ms` }}
      className="relative hidden shrink-0 overflow-hidden transition-[width] ease-[cubic-bezier(0.2,0.8,0.3,1)] motion-reduce:transition-none md:flex"
    >
      {/* Список прижат к ЛЕВОМУ краю дока и держит свои 232 точки, пока колонка
          сжимается: край дока едет вправо, панель едет с ним и уходит за рейку
          целиком — не ужимаясь и не переверстываясь на ходу.

          `inert` снимает уезжающую панель с клавиатуры и со скринридера в тот
          же миг, когда её перестали показывать: доля секунды, пока она видна на
          пути к краю, — время анимации, а не время, когда с ней ещё работают. */}
      {mounted && (
        <div
          data-testid="dm-drawer"
          inert={!open}
          style={{ width: DM_DOCK_WIDTH }}
          className="absolute inset-y-0 left-0 flex border-l border-line"
        >
          <DmList />
        </div>
      )}
    </div>
  );
}
