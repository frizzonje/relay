import type { CallReplyResult, CallStartResult, CallStateRelay } from '@relay/shared';
import { getSocket } from '@/lib/socket';
import { joinVoice, leaveVoice, onVoiceLeft, voiceRoom } from '@/lib/voice';
import { isCamOn, toggleCamera } from '@/lib/voice/camera';

/**
 * Голосовая жизнь вызова: комната беседы, вход в неё и выход из неё.
 *
 * Отдельно от `@/lib/voice` намеренно. Дирижёр эфира отвечает на вопрос «как
 * ведётся разговор», и человек в нём заходит в КАНАЛ — щёлкнув по нему. Вызов
 * устроен иначе: комнаты до ответа нет вовсе, входа по клику не бывает, а
 * кончается разговор не кнопкой «выйти», а уходом второго. Живи это в
 * `voice.ts`, у дирижёра завелась бы вторая личность — с двумя разными
 * ответами на «почему я вдруг в комнате».
 *
 * **Садится в комнату клиент, а не сервер.** Сервер мог бы вписать оба сокета
 * в комнату сам, и соблазн велик: тогда «оба сели» не зависело бы от того,
 * доехало ли событие. Но сесть в голосовую комнату — это не строчка в карте
 * комнат, а взятый микрофон, поднятые транспорты и готовность отвечать на
 * offer. Ничего этого сервер за вкладку не сделает, и вписанный им сокет
 * оказался бы в комнате молча: для собеседника он есть, а звука от него нет —
 * ровно то состояние, которое в relay уже разбирали как «в канале, но не
 * слышно». Поэтому сервер делает единственное, чего клиент не может: открывает
 * комнату, называет её адрес обоим (`call-state` с `accepted`) и стережёт
 * дверь. Садятся — сами.
 *
 * Отсюда же второе правило: садится РОВНО ТА вкладка, что звонила или
 * отвечала. «Принято» приезжает на все устройства обоих — оно гасит входящий
 * там, где трубку не брали, — и сядь по нему каждая вкладка, человека было бы
 * слышно дважды, а сам он слышал бы себя эхом. Владение вызовом — единственное
 * состояние этого файла, и оно заявляется ДО отправки «принять» (см.
 * `answerCall`).
 */

/**
 * Вызов, который ведёт именно эта вкладка: она его набрала или на него
 * ответила. Пусто — все приходящие «принято» относятся к чужим устройствам.
 */
let mine: string | null = null;

/** Комната беседы, в которой эта вкладка сидит. Пусто — разговора нет. */
let room: string | null = null;

/**
 * Поколение посадки: `drop` его сдвигает. Тот же приём, что у переездов между
 * каналами в `voice.ts`, и заведён он по той же причине — посадка не одно
 * действие, а ожидание длиной в микрофонное разрешение, и разговор успевает
 * кончиться прямо посреди неё.
 */
let seating = 0;

let initialized = false;

/** Комната идущего разговора — или `null`. */
export function callRoom(): string | null {
  return room;
}

/** Вызов, которым владеет эта вкладка, — или `null`. */
export function ownedCall(): string | null {
  return mine;
}

/**
 * Позвонить. Владение заявляем по ответу сервера, и здесь это безопасно:
 * `accepted` не может обогнать подтверждение — между ними стоит человек,
 * который берёт трубку.
 */
export function dialCall(fingerprint: string, video = false): Promise<CallStartResult> {
  return new Promise((resolve) => {
    getSocket().emit('call-start', { fingerprint, video }, (res) => {
      if (res.ok) mine = res.ringId;
      resolve(res);
    });
  });
}

/**
 * Принять входящий — только отсюда.
 *
 * Владение заявляется ДО отправки, и это не перестраховка: рассылка
 * `call-state` и подтверждение «принять» идут по одному сокету, причём
 * рассылка уходит первой. Заяви вкладка владение по подтверждению — «принято»
 * приехало бы в никуда, и разговор не собрался бы ровно на том устройстве, где
 * нажали «принять».
 */
export function answerCall(ringId: string): Promise<CallReplyResult> {
  mine = ringId;
  return new Promise((resolve) => {
    getSocket().emit('call-accept', { ringId }, (res) => {
      // Проигранная гонка (успели отменить, вышел таймаут, ответили с другого
      // устройства): владение снимаем — садиться будет некуда.
      if (!res.ok) forget(ringId);
      resolve(res);
    });
  });
}

/**
 * Положить трубку самому. Из комнаты выходим у себя, а разговор кончает
 * сервер: он выведет из неё и второго — комната на одного это не звонок на
 * удержании, а человек, слушающий тишину.
 *
 * Раньше функция выходила по одному лишь `!room` и в этом случае не делала
 * ничего — а значит не умела бросить вызов, который ЕЩЁ не стал разговором:
 * набрали и передумали до ответа, или ответили и ждём посадки в комнату.
 * `mine` в этом окне уже стоит (см. `dialCall`/`answerCall`), комнаты ещё нет,
 * и кнопка «отбой» экрана дозвона слала бы в никуда. `call-cancel` на чужой
 * или уже settled `ringId` (например, если accept успел пройти раньше, чем
 * дошёл этот клик) вернётся `{ ok: false, error: 'unknown' }` — сервер так
 * отвечает на любую проигранную гонку, и здесь это не ошибка, а не о чем
 * рассказывать.
 */
export function hangUp(): void {
  if (room) {
    drop();
    return;
  }
  const ringId = mine;
  if (!ringId) return;
  mine = null;
  getSocket().emit('call-cancel', { ringId }, () => {});
}

/**
 * Отбой вызова, названного по имени, — того, который набрали на ДРУГОМ
 * устройстве этой же личности.
 *
 * `hangUp()` выше умеет бросить только СВОЙ вызов (`mine` — заявленный этой
 * вкладкой при наборе или ответе). Но `call-state{ringing}` уходит на все
 * устройства звонящего (§4.2 протокола), и экран дозвона по нему открывается и
 * там, где не набирали: у той вкладки `mine` пуст, `hangUp()` промолчал бы, и
 * кнопка «Отбой» гасила бы экран, оставив вызов звонить у собеседника —
 * вранье ровно в том месте, где человек уверен, что положил трубку.
 *
 * Отправить отбой отсюда можно и нужно: право на него сервер проверяет по
 * ЛИЧНОСТИ, а не по сокету (`RingDesk.cancel` → `press(identityId, …, 'from')`),
 * то есть второе устройство звонящего — законная сторона вызова. Проигранная
 * гонка (успели принять, вышел таймаут, отбили с третьего устройства) вернётся
 * обычным `{ ok: false, error: 'unknown' }` — рассказывать о ней нечего.
 */
export function cancelCall(ringId: string): void {
  forget(ringId);
  getSocket().emit('call-cancel', { ringId }, () => {});
}

/**
 * Отклонить входящий (задача 7 плана B) — кнопка тоста, а не набора.
 *
 * `mine` трогать нечего: владение вызовом эта вкладка заявляет только приняв
 * его (`answerCall`) или набрав сам (`dialCall`) — отказ от разговора,
 * который и не начинался, ничьей меткой занятости не был. `call-ended` по
 * этому отбою всё равно придёт (протокол §4.2 — обеим сторонам), но нашей
 * вкладке в нём читать нечего: `mine` в ней и так пуст.
 *
 * Ack не проверяем по той же причине, что и у `cancelCall`: чужая или уже
 * решённая гонка вернётся `{ ok: false, error: 'unknown' }`, а тост к этому
 * моменту уже закрыт нажатием кнопки — рассказывать там уже некому.
 */
export function declineCall(ringId: string): void {
  getSocket().emit('call-decline', { ringId }, () => {});
}

/** Подписка на события вызова. Зовётся один раз на приложение. */
export function initCall() {
  if (initialized) return;
  initialized = true;
  const socket = getSocket();

  socket.on('call-state', (payload) => {
    void seat(payload);
  });
  // Разговор кончился: собеседник ушёл либо он переехал на другое устройство.
  // Из комнаты сервер уже вывел — здесь остаётся отпустить микрофон и снять
  // экран звонка.
  socket.on('call-over', ({ room: over }) => {
    if (over !== room) return;
    drop();
  });
  // Вызов кончился, не став разговором. Опоздавшее «принято» по нему в комнату
  // уже не посадит.
  socket.on('call-ended', ({ ringId }) => forget(ringId));
  // В комнату беседы не пустили. Для законного участника это один случай:
  // садиться было слишком долго (первый в жизни запрос доступа к микрофону
  // висит на экране минуту), и комнату успел закрыть сторож. Тост тут — не
  // ответ: вкладка в комнату не вошла, а значит и `call-over` до неё не
  // доедет никогда, и экран звонка с открытым микрофоном стоял бы над
  // разговором, которого нет.
  socket.on('voice-refused', ({ reason }) => {
    if (reason !== 'not-in-call' || !room) return;
    drop();
  });

  // Из комнаты беседы выходят не только концом разговора. Кнопка «Отбой» в
  // панели голоса, «Выйти» в сайдбаре и мобильной навигации, хоткей, щелчок по
  // соседнему каналу — все они зовут `leaveVoice` напрямую и про этот файл не
  // знают. Не узнавай он о таком выходе, `room`/`mine` остались бы набитыми до
  // конца сеанса: серверный `call-over` приезжал бы в комнату, которую сокет
  // уже покинул, а следующий «Отбой» по ещё не отвеченному вызову ушёл бы
  // веткой разговора — то есть выдернул бы человека из канала, в котором он
  // сидит на самом деле, вместо отмены дозвона.
  //
  // Сверка комнаты обязательна: этот же хук приходит на переезд между обычными
  // каналами и на мягкий выход ВНУТРИ входа в саму комнату беседы (`joinVoice`
  // покидает прежний канал сам, ещё до того как мы в новой). Разбери мы всякий
  // выход — посадка в разговор сносила бы сама себя.
  //
  // Отправлять серверу отдельно нечего: `leaveVoice` шлёт `leave`, а сервер по
  // освободившемуся месту кончает беседу обоим (`voice-sessions.ts`, `endCall`).
  onVoiceLeft((left) => {
    if (left !== room) return;
    forgetRoom();
  });
}

/**
 * Выйти из разговора у себя: отпустить микрофон, снять экран звонка и забыть
 * вызов. Собеседника кончает сервер — своим уходом мы ему об этом и говорим.
 */
function drop(): void {
  // Комнату забываем ДО выхода, и это не косметика: `leaveVoice` оповестит
  // подписчиков `onVoiceLeft`, среди которых мы сами. К этому моменту нашей
  // комнаты уже нет — сверка в подписке не совпадёт, и второго круга не будет.
  forgetRoom();
  leaveVoice(true);
}

/**
 * Забыть разговор, не трогая эфир: комната, владение и поколение посадки.
 * Отдельно от `drop`, потому что выйти из эфира могли и без нас — тогда звать
 * `leaveVoice` изнутри его же уборки было бы вторым кругом (см. `onVoiceLeft`).
 */
function forgetRoom(): void {
  room = null;
  mine = null;
  seating += 1;
}

/** Забыть свой вызов, если речь о нём же. */
function forget(ringId: string): void {
  if (mine === ringId) mine = null;
}

/**
 * Сесть в комнату беседы. Единственная дверь в разговор — принятый вызов: ни
 * «звонит», ни чужое устройство сюда не ведут.
 */
async function seat(payload: CallStateRelay): Promise<void> {
  if (payload.state !== 'accepted' || payload.ringId !== mine || !payload.room) return;
  const gen = ++seating;
  room = payload.room;
  // Подпись комнаты — имя собеседника: беседа называется человеком, а не
  // адресом, который он всё равно никогда не видел.
  const seated = await joinVoice(payload.room, payload.peer.nick);
  // Пока садились, разговор мог кончиться: собеседник ушёл, сервер отказал.
  // Сам вход `joinVoice` в этом случае бросает (у него своё поколение), но
  // микрофон, взятый по дороге, остаётся открытым — и человек, у которого
  // экран звонка уже погас, продолжает быть слышен. Отпускаем его здесь — но
  // только если эфир НИЧЕЙ: ни разговора (`room`), ни обычного канала
  // (`voiceRoom()`).
  //
  // Второе условие — не перестраховка. Микрофонное разрешение одно на все
  // заходы (`ensureLocalStream`), и первое в жизни висит на экране минуту:
  // звонок успевает кончиться, человек — щёлкнуть голосовой канал, и его
  // заход ждёт то же самое разрешение. Разбуди их одно `getUserMedia` —
  // наша опоздавшая уборка звала бы `leaveVoice(true)` поверх чужого живого
  // захода: он сдвигает общее поколение и гасит общий микрофон, а тот бросил
  // бы вход молча уже после того, как сцена канала открылась. Свой `room` про
  // это не знает ничего: он пуст ровно потому, что разговора больше нет.
  if (gen !== seating) {
    if (!room && !voiceRoom()) leaveVoice(true);
    return;
  }
  // Вход мог и не состояться: в движке нет WebRTC, человек не дал микрофон, нас
  // обогнал следующий заход. Считать себя в разговоре, в который не вошли, —
  // худшее из двух вранья: экран звонка стоит, `hangUp` уже ничего не пошлёт
  // (выходить неоткуда), а собеседник ждёт в комнате того, кто не придёт.
  // Комнату ему закроет сторож на сервере — но врать себе нельзя и до него.
  if (!seated) {
    if (room === payload.room) {
      room = null;
      mine = null;
    }
    return;
  }
  // Камеру открываем ровно тогда, когда о видео договорились двое: `video`
  // приезжает от сервера уже зажатым настройкой инсталляции. Голосовой звонок
  // камеры не спрашивает вовсе — не «выключает по умолчанию», а не трогает.
  // Проверка комнаты — на случай, если пока брали микрофон, разговор кончился.
  if (payload.video && room === payload.room && !isCamOn()) await toggleCamera();
}
