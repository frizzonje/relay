import { describe, expect, it } from 'vitest';
import { excerpt, highlight } from './search';

/**
 * Как найденное выглядит в списке результатов. Проверяем ровно то, что человек
 * видит глазами: подсвечено именно то слово, из-за которого строка нашлась, и
 * от длинной реплики показан кусок вокруг него, а не её начало.
 */

/** Подсвеченные куски — то, что в разметке станет `<mark>`. */
function marked(text: string, terms: string[]): string[] {
  return highlight(text, terms)
    .filter((s) => s.hit)
    .map((s) => s.text);
}

describe('подсветка', () => {
  it('слово подсвечивается целиком, даже если набрали его начало', () => {
    // Сервер нашёл эту реплику по «дач», и подчёркнутый огрызок посреди слова
    // читался бы как опечатка, а не как совпадение.
    expect(marked('поедем на дачу в субботу', ['дач'])).toEqual(['дачу']);
  });

  it('регистр не мешает', () => {
    expect(marked('Дача и ДАЧНИКИ', ['дач'])).toEqual(['Дача', 'ДАЧНИКИ']);
  });

  it('середина слова не считается совпадением — сервер ищет не так', () => {
    expect(marked('передача мяча', ['дач'])).toEqual([]);
  });

  it('текст между находками сохраняется целиком', () => {
    const text = 'дача, море, дачники';
    expect(
      highlight(text, ['дач'])
        .map((s) => s.text)
        .join(''),
    ).toBe(text);
  });

  it('без слов подсвечивать нечего', () => {
    expect(highlight('что-нибудь', [])).toEqual([{ text: 'что-нибудь', hit: false }]);
  });
});

describe('выжимка длинной реплики', () => {
  const long = `${'слово '.repeat(60)}находка ${'хвост '.repeat(60)}`;

  it('короткое сообщение показывается как есть', () => {
    expect(excerpt('коротко и ясно', ['коротко'])).toBe('коротко и ясно');
  });

  it('от длинного показывается кусок вокруг найденного', () => {
    const cut = excerpt(long, ['находка']);
    expect(cut).toContain('находка');
    expect(cut.length).toBeLessThan(long.length);
    // Обрезано с обеих сторон — и об этом сказано, а не молча.
    expect(cut.startsWith('…')).toBe(true);
    expect(cut.endsWith('…')).toBe(true);
  });

  it('слова не рвутся посередине', () => {
    const cut = excerpt(long, ['находка']).replace(/^…|…$/g, '');
    for (const word of cut.trim().split(/\s+/)) {
      expect(['слово', 'находка', 'хвост']).toContain(word);
    }
  });
});
