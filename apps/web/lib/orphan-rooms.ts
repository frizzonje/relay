import { isCallRoom, type VoicePresence } from '@relay/shared';

/**
 * Занятые эфиры, за которыми не стоит канала реестра, — те временные строки,
 * что сайдбар дорисовывает под списком голосовых каналов, чтобы никого не
 * потерять (канал удалили, пока в нём сидят). Отдельная чистая функция: это
 * правила «что считать потерянным эфиром», а не разметка, и проверяются они без
 * рендера (lib/orphan-rooms.test.ts).
 *
 * Правил три, и третье — не оптимизация:
 *   • комнату, за которой стоит видимый канал, рисует основной список — второй
 *     раз она тут не нужна;
 *   • своя комната остаётся даже пустой: в ней сидим мы сами, и не показать её
 *     значило бы соврать;
 *   • комната разговора двоих не показывается НИКОГДА. Она не канал и никогда
 *     им не была: сервер шлёт её в присутствии обоим собеседникам (правило
 *     «своя комната» в `presenceFor`), у неё машинное имя `voice:dm-…`, войти
 *     в неё по клику нельзя — сервер запрёт, — а нарисованная строкой в списке
 *     каналов сервера она выглядит как канал, который кто-то создал.
 */
export function orphanVoiceRooms(
  presence: VoicePresence,
  channelSlugs: ReadonlySet<string>,
  ownRoom: string | null,
): string[] {
  return Object.keys(presence).filter(
    (room) =>
      !channelSlugs.has(room) &&
      !isCallRoom(room) &&
      ((presence[room]?.length ?? 0) > 0 || room === ownRoom),
  );
}
