/**
 * Identicon — картинка личности, выведенная из отпечатка ключа.
 *
 * Зачем он вообще: ники в 1.0 свободные и НЕ уникальные, так что двух «Ань»
 * различает только ключ. Читать шестнадцать шестнадцатеричных цифр глазами при
 * каждом сообщении никто не станет — а вот заметить, что у сегодняшней «Ани»
 * другой рисунок, человек может боковым зрением. Это и есть его работа: не
 * доказать личность (доказывает подпись), а сделать подмену заметной.
 *
 * Отсюда два требования, и они важнее красоты:
 *
 *   1. **Детерминированность.** Один отпечаток — один рисунок, всегда и везде,
 *      на любом клиенте и в любой версии. Поэтому вычисление живёт здесь одно,
 *      а не растекается по компонентам, и меняться ему нельзя: смена алгоритма
 *      перерисует всех людей разом и обесценит именно ту память, ради которой
 *      он существует.
 *   2. **Различимость.** Рисунок должен разъезжаться от малого изменения
 *      входа, а не давать «похожие пятна» на похожие ключи. Отпечаток уже
 *      выведен из SHA-256, так что биты распределены равномерно сами — но
 *      разложить их по клеткам надо так, чтобы участвовали ВСЕ восемь байт, а
 *      не первые два (см. ниже: на этом первая версия и попалась).
 *
 * Форма — симметричная сетка 5×5: левая половина рисуется битами, правая
 * зеркалит её. Симметрия здесь не украшение, а способ вдвое сократить число
 * клеток, оставив рисунок опознаваемым: человек запоминает силуэт, а не 25
 * независимых точек.
 */

/** Сторона сетки. Пять — потому что три слишком бедно, семь уже не силуэт. */
export const GRID = 5;

/** Сколько бит нужно рисунку: три левых столбца по пять клеток. */
const CELLS = Math.ceil(GRID / 2) * GRID;

export interface Identicon {
  /** Клетки построчно, слева направо: `true` — закрашено. */
  cells: boolean[];
  /** Цвет закрашенных клеток. */
  color: string;
}

/** Отпечаток `a1b2-c3d4-…` → байты. Всё, что не шестнадцатеричное, отбрасываем. */
function bytesOf(fingerprint: string): number[] {
  const hex = fingerprint.toLowerCase().replace(/[^0-9a-f]/g, '');
  const out: number[] = [];
  for (let i = 0; i + 1 < hex.length; i += 2) out.push(parseInt(hex.slice(i, i + 2), 16));
  return out;
}

/**
 * Рисунок по отпечатку. Пустой или битый отпечаток даёт пустую сетку, а не
 * исключение: identicon рисуется в ленте на каждое сообщение, и уронить её
 * из-за одной кривой строки было бы обменом несоразмерным.
 */
export function identiconOf(fingerprint: string): Identicon {
  const bytes = bytesOf(fingerprint);
  if (!bytes.length) return { cells: new Array(GRID * GRID).fill(false), color: 'hsl(0 0% 50%)' };

  // Клетки берут байты по кругу, а не подряд из первых двух. Разница не
  // теоретическая: клеток пятнадцать, и «подряд» означало бы, что рисунок
  // выведен из двух байт отпечатка из восьми, — отпечаток вида `ffff-…` давал
  // бы сплошной квадрат, а половина оставшихся байт не участвовала бы вовсе.
  // Сдвиг зависит и от круга, чтобы второй проход по тому же байту не повторил
  // первый.
  const len = bytes.length;
  const bit = (i: number) => ((bytes[i % len] >> ((Math.floor(i / len) * 3 + i) % 8)) & 1) === 1;

  const half = Math.ceil(GRID / 2);
  const left: boolean[] = Array.from({ length: CELLS }, (_, i) => bit(i));

  const cells: boolean[] = [];
  for (let row = 0; row < GRID; row += 1) {
    for (let col = 0; col < GRID; col += 1) {
      // Правая половина — зеркало левой: столбец GRID-1-col.
      const source = col < half ? col : GRID - 1 - col;
      cells.push(left[row * half + source]);
    }
  }

  // Цвет — из хвоста отпечатка, чтобы он не зависел от битов рисунка: иначе
  // два похожих силуэта получали бы и похожий цвет, а их-то и надо различать.
  // Насыщенность и светлота фиксированы: палитра relay холодная и приглушённая,
  // а identicon не должен спорить с интерфейсом яркостью.
  const hue = (bytes[bytes.length - 1] * 360) / 256;
  return { cells, color: `hsl(${hue.toFixed(0)} 55% 62%)` };
}
