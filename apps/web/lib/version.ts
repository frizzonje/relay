/**
 * Версия клиента — та, под которой собран этот бандл.
 *
 * Читается из окружения сборки (`NEXT_PUBLIC_RELAY_VERSION`), а не с сервера, и
 * в этом весь смысл: браузер держит уже скачанный код, и после обновления
 * сервера открытая вкладка остаётся на прежнем. Номер, вшитый в сам бандл, —
 * единственное, чем такая вкладка отличается от свежей.
 *
 * Пустая строка — сборка из исходников: номера релиза у неё нет.
 */
export function clientVersion(): string {
  return (process.env.NEXT_PUBLIC_RELAY_VERSION ?? '').trim();
}
