'use client';

import type { CallPerson } from '@relay/shared';
import { getSfx } from '@/lib/sfx';
import { tx } from '@/lib/i18n';
import { setting } from '@/stores/config';
import { isChannelLoud, useNotifyStore } from '@/stores/notify';

/**
 * Уведомление о входящем сообщении — одна точка входа на оба сигнала.
 *
 * Вспышка в сайдбаре идёт всегда и на каждое сообщение: она беззвучна и стоит
 * одного мигания точки. Звук — только там, где его разрешили (stores/notify, по
 * умолчанию молчат все); общий мут и выбор устройства вывода уже держит lib/sfx,
 * так что наушники в панели голоса глушат и этот тик тоже.
 *
 * Пауза между тиками — чтобы живая переписка не превращалась в очередь.
 * Разговор на пять реплик подряд стоит одного сигнала: он сообщает «в канале
 * что-то происходит», а не считает сообщения. Сервер уже склеивает свои пинги
 * активности (chat-activity, 80 мс) — этого мало для человеческого темпа речи.
 * Вспышку пауза не касается: считать реплики глазами не мешает никому.
 */
const COOLDOWN_MS = 1500;

// −∞, а не 0: первый за сеанс тик паузой не связан.
let lastAt = -Infinity;

/**
 * Разрешает ли инсталляция этот сигнал.
 *
 * Три настройки складываются так: `notifications.soundEnabled` — общий рубильник
 * над всеми входящими сигналами, остальные две уточняют его для обращения по
 * имени и для личной реплики. Своё отправленное сообщение (`notifySent`) под
 * рубильник не попадает намеренно: это не уведомление о чужом, а отклик на
 * собственное нажатие Enter, и выключать его вместе с чужими сигналами значило
 * бы выключить не то, о чём просили.
 *
 * Умолчания каталога — «всё включено», то есть сегодняшнее поведение relay:
 * молчат по-прежнему только те каналы, которым человек сам не разрешал звук.
 */
function allowed(key?: string): boolean {
  if (!setting<boolean>('notifications.soundEnabled')) return false;
  return key === undefined || setting<boolean>(key);
}

export function notifyMessage(slug: string) {
  if (!slug) return;
  const s = useNotifyStore.getState();
  s.notePing(slug);
  if (!isChannelLoud(s, slug) || !allowed()) return;
  const now = Date.now();
  if (now - lastAt < COOLDOWN_MS) return;
  lastAt = now;
  getSfx().play('receive');
}

/**
 * Своя реплика ушла. Не уведомление, а отклик на действие: мимо настроек
 * канала (заглушить чужой разговор — не то же самое, что заглушить себе
 * подтверждение) и мимо паузы (пауза склеивает поток чужих реплик, а свои
 * человек отправляет по одной, нажимая на Enter). Общий мут и наушники в
 * панели голоса главнее по-прежнему — их держит lib/sfx.
 */
export function notifySent() {
  getSfx().play('send');
}

/**
 * Тебя назвали — звук идёт мимо настройки канала и мимо паузы.
 *
 * Звук канала — это про «там что-то происходит», и молчание по умолчанию тут
 * правильно: чужой разговор не обязан тебя дёргать. Обращение по имени —
 * другое дело: его адресовали лично, и промолчать о нём потому, что канал
 * заглушён, значит заглушить не канал, а человека. Общий мут (наушники в
 * панели голоса) при этом по-прежнему главнее — его держит lib/sfx.
 *
 * Паузу между тиками мы всё же двигаем: назвали и тут же написали пять реплик
 * — вызов уже прозвучал, догонять его чередой сигналов незачем.
 */
export function notifyMention(slug: string) {
  if (!slug) return;
  useNotifyStore.getState().notePing(slug);
  lastAt = Date.now();
  if (!allowed('notifications.mentionSound')) return;
  getSfx().play('message');
}

/**
 * Личная реплика. Звучит она так же, как обращение по имени, — и по той же
 * причине: адресовали лично. Настройка при этом своя (`notifications.directSound`):
 * инсталляция, выключившая звук личных бесед, не обязана заодно молчать на
 * упоминания в общем канале.
 *
 * Вспышку и паузу двигаем в любом случае — они беззвучны и не спрашивают
 * разрешения ни у кого.
 */
export function notifyDirect(slug: string) {
  if (!slug) return;
  useNotifyStore.getState().notePing(slug);
  lastAt = Date.now();
  if (!allowed('notifications.directSound')) return;
  getSfx().play('message');
}

/**
 * Тик в ответ на включение звука канала. Настройка, которую нельзя проверить,
 * не проверяется никогда: ждать чужого сообщения, чтобы узнать, не выкручена ли
 * система на ноль, — плохая сделка. Мимо канала и паузы: это не уведомление.
 */
export function previewMessageSound() {
  if (!allowed()) return;
  getSfx().play('receive');
}

/** Отменяемое системное уведомление — см. `notifyCall`. */
export interface CallNotification {
  /** Убрать уже показанное окошко либо отменить ещё не показанное. */
  close: () => void;
}

/** Ничего не показывал и нечего закрывать — общий ранний выход `notifyCall`. */
const NOTHING: CallNotification = { close: () => {} };

/**
 * Входящий звонок при свёрнутом окне — единственный во всём клиенте вызов
 * `Notification` API (см. `notifications.desktopEnabled` в каталоге, где это
 * написано явно). Тост (`IncomingToast.tsx`) виден и так, пока вкладка
 * открыта на экране, — это окошко для случая, ради которого честное
 * ограничение и стоит на экране исходящего: relay не пуш-сервис, и без вкладки
 * в фокусе входящий иначе остаётся замеченным только звуком.
 *
 * Показываем, только когда `document.visibilityState === 'hidden'`: на
 * видимой вкладке тост уже на экране, и системное окошко поверх него не
 * рассказало бы ничего нового — только продублировало бы то, что и так видно.
 *
 * Разрешение спрашиваем здесь же, а не заранее отдельной кнопкой: отдельная
 * кнопка «разрешить уведомления» без звонка, который их оправдывает, — это
 * запрос в пустоту, на который человек отвечает бездумным «нет». Плата за
 * это честная: первый в жизни звонок, пришедший в свёрнутое окно, может не
 * показать окошко (пока браузер спрашивает разрешение, вызов успевает
 * кончиться) — зато все следующие, если разрешили, покажут его сразу.
 *
 * Возвращает ручку закрытия, а не ничего: тост обязан убрать своё окошко
 * ровно тогда, когда убирает себя (принят, отклонён, отбой, не ответили,
 * обрыв сокета — общий список `stores/ring.ts`), а не ждать, пока оно
 * истечёт само. `close()` безопасен и до того, как окошко реально возникло:
 * если разрешение спрашивается асинхронно и вызов кончился раньше ответа,
 * флаг `cancelled` не даёт показать окошко о вызове, которого уже нет.
 */
export function notifyCall(from: CallPerson, video: boolean): CallNotification {
  if (typeof Notification === 'undefined') return NOTHING;
  if (document.visibilityState !== 'hidden') return NOTHING;
  if (!setting<boolean>('notifications.desktopEnabled')) return NOTHING;

  let cancelled = false;
  let shown: Notification | null = null;
  const show = () => {
    if (cancelled) return;
    shown = new Notification(from.nick, {
      body: tx(video ? 'call.videoCall' : 'call.incoming.ringing'),
      tag: 'relay-call',
    });
    // Клик по системному окошку возвращает к вкладке, где и лежит тост с
    // настоящими «принять»/«отклонить» — окошко само эти кнопки не несёт.
    shown.onclick = () => {
      window.focus();
      shown?.close();
    };
  };

  if (Notification.permission === 'granted') {
    show();
  } else if (Notification.permission === 'default') {
    void Notification.requestPermission().then((permission) => {
      if (permission === 'granted') show();
    });
  }

  return {
    close: () => {
      cancelled = true;
      shown?.close();
    },
  };
}
