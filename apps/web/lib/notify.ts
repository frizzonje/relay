'use client';

import type { CallPerson } from '@relay/shared';
import { getSfx } from '@/lib/sfx';
import { inShell, shellRingStart, shellRingStop } from '@/lib/shell-bridge';
import { tx } from '@/lib/i18n';
import { setting } from '@/stores/config';
import { isChannelLoud, useNotifyStore } from '@/stores/notify';

/**
 * Уведомление о входящем сообщении — одна точка входа на оба сигнала.
 *
 * Вспышка в сайдбаре идёт всегда и на каждое сообщение: она беззвучна и стоит
 * одного мигания точки. Звук — только там, где его разрешили (stores/notify, по
 * умолчанию молчат все); общий мут и выбор устройства вывода уже держит lib/sfx,
 * так что наушники в панели голоса глушат и этот тик тоже.
 *
 * Пауза между тиками — чтобы живая переписка не превращалась в очередь.
 * Разговор на пять реплик подряд стоит одного сигнала: он сообщает «в канале
 * что-то происходит», а не считает сообщения. Сервер уже склеивает свои пинги
 * активности (chat-activity, 80 мс) — этого мало для человеческого темпа речи.
 * Вспышку пауза не касается: считать реплики глазами не мешает никому.
 */
const COOLDOWN_MS = 1500;

// −∞, а не 0: первый за сеанс тик паузой не связан.
let lastAt = -Infinity;

/**
 * Разрешает ли инсталляция этот сигнал.
 *
 * Три настройки складываются так: `notifications.soundEnabled` — общий рубильник
 * над всеми входящими сигналами, остальные две уточняют его для обращения по
 * имени и для личной реплики. Своё отправленное сообщение (`notifySent`) под
 * рубильник не попадает намеренно: это не уведомление о чужом, а отклик на
 * собственное нажатие Enter, и выключать его вместе с чужими сигналами значило
 * бы выключить не то, о чём просили.
 *
 * Умолчания каталога — «всё включено», то есть сегодняшнее поведение relay:
 * молчат по-прежнему только те каналы, которым человек сам не разрешал звук.
 */
function allowed(key?: string): boolean {
  if (!setting<boolean>('notifications.soundEnabled')) return false;
  return key === undefined || setting<boolean>(key);
}

export function notifyMessage(slug: string) {
  if (!slug) return;
  const s = useNotifyStore.getState();
  s.notePing(slug);
  if (!isChannelLoud(s, slug) || !allowed()) return;
  const now = Date.now();
  if (now - lastAt < COOLDOWN_MS) return;
  lastAt = now;
  getSfx().play('receive');
}

/**
 * Своя реплика ушла. Не уведомление, а отклик на действие: мимо настроек
 * канала (заглушить чужой разговор — не то же самое, что заглушить себе
 * подтверждение) и мимо паузы (пауза склеивает поток чужих реплик, а свои
 * человек отправляет по одной, нажимая на Enter). Общий мут и наушники в
 * панели голоса главнее по-прежнему — их держит lib/sfx.
 */
export function notifySent() {
  getSfx().play('send');
}

/**
 * Тебя назвали — звук идёт мимо настройки канала и мимо паузы.
 *
 * Звук канала — это про «там что-то происходит», и молчание по умолчанию тут
 * правильно: чужой разговор не обязан тебя дёргать. Обращение по имени —
 * другое дело: его адресовали лично, и промолчать о нём потому, что канал
 * заглушён, значит заглушить не канал, а человека. Общий мут (наушники в
 * панели голоса) при этом по-прежнему главнее — его держит lib/sfx.
 *
 * Паузу между тиками мы всё же двигаем: назвали и тут же написали пять реплик
 * — вызов уже прозвучал, догонять его чередой сигналов незачем.
 */
export function notifyMention(slug: string) {
  if (!slug) return;
  useNotifyStore.getState().notePing(slug);
  lastAt = Date.now();
  if (!allowed('notifications.mentionSound')) return;
  getSfx().play('message');
}

/**
 * Личная реплика. Звучит она так же, как обращение по имени, — и по той же
 * причине: адресовали лично. Настройка при этом своя (`notifications.directSound`):
 * инсталляция, выключившая звук личных бесед, не обязана заодно молчать на
 * упоминания в общем канале.
 *
 * Вспышку и паузу двигаем в любом случае — они беззвучны и не спрашивают
 * разрешения ни у кого.
 */
export function notifyDirect(slug: string) {
  if (!slug) return;
  useNotifyStore.getState().notePing(slug);
  lastAt = Date.now();
  if (!allowed('notifications.directSound')) return;
  getSfx().play('message');
}

/**
 * Тик в ответ на включение звука канала. Настройка, которую нельзя проверить,
 * не проверяется никогда: ждать чужого сообщения, чтобы узнать, не выкручена ли
 * система на ноль, — плохая сделка. Мимо канала и паузы: это не уведомление.
 */
export function previewMessageSound() {
  if (!allowed()) return;
  getSfx().play('receive');
}

/** Отменяемое системное уведомление — см. `notifyCall`. */
export interface CallNotification {
  /** Убрать уже показанное окошко либо отменить ещё не показанное. */
  close: () => void;
}

/** Мигающий заголовок вкладки — см. `flashTitle`. */
export interface TitleFlash {
  /** Вернуть настоящий заголовок и больше его не трогать. */
  stop: () => void;
}

/** Полсекунды — заметно, но не бьёт по глазам; секунда на полный цикл. */
const FLASH_MS = 1000;

/**
 * Мигать заголовком вкладки, пока её не смотрят.
 *
 * У свёрнутой вкладки от relay остаётся ровно одна видимая вещь — заголовок в
 * полосе табов: ни тоста, ни лица звонящего там нет. Звук говорит, что
 * что-то случилось, но не говорит, ГДЕ; заголовок говорит.
 *
 * Два правила, ради которых эта функция вообще существует отдельно от
 * `document.title = ...` в вызывающем коде:
 *
 *  1. Настоящий заголовок обязан вернуться. И когда вызов кончился (`stop()`),
 *     и когда на вкладку просто ПОСМОТРЕЛИ: мигающая полоса таба поверх
 *     открытого тоста — это не уведомление, а мусор; а забытая навсегда — то
 *     самое, из-за чего вкладку потом закрывают.
 *  2. Мигание не начинается на видимой вкладке и подхватывается, если её
 *     свернули уже посреди звонка: интересна не вкладка в момент звонка, а
 *     вкладка в момент взгляда.
 *
 * Разрешения не спрашивает и настройкой не гасится — как и вспышка в
 * сайдбаре: это не системное окошко поверх чужих окон, а собственный
 * заголовок, беззвучный и целиком внутри вкладки.
 */
export function flashTitle(text: string): TitleFlash {
  if (typeof document === 'undefined') return { stop: () => {} };

  const real = document.title;
  let timer: ReturnType<typeof setInterval> | null = null;
  let shown = false;

  const tick = () => {
    shown = !shown;
    document.title = shown ? text : real;
  };

  const sync = () => {
    if (document.visibilityState === 'hidden') {
      if (timer !== null) return;
      tick(); // первый кадр сразу: ждать секунду, чтобы начать, незачем
      timer = setInterval(tick, FLASH_MS);
      return;
    }
    if (timer !== null) {
      clearInterval(timer);
      timer = null;
    }
    shown = false;
    document.title = real;
  };

  document.addEventListener('visibilitychange', sync);
  sync();

  return {
    stop: () => {
      // Слушателя снимаем ПЕРВЫМ: оставленный, он воскресил бы вспышку на
      // давно кончившемся вызове, стоило свернуть вкладку.
      document.removeEventListener('visibilitychange', sync);
      if (timer !== null) clearInterval(timer);
      timer = null;
      shown = false;
      document.title = real;
    },
  };
}

/**
 * Показывать ли системное окошко об этом вызове. Одно правило на всех, кто его
 * умеет показать (вкладка и нативная оболочка), — потому что двое, решающие
 * это независимо, однажды решат «да» оба, и об одном звонке придёт два
 * уведомления.
 *
 * Условий два: вкладку/окно не смотрят (на видимой всё уже сказал тост) и
 * инсталляция окошки разрешает (`notifications.desktopEnabled`).
 */
function wantsSystemNotice(): boolean {
  if (typeof document === 'undefined') return false;
  if (document.visibilityState !== 'hidden') return false;
  return setting<boolean>('notifications.desktopEnabled');
}

/**
 * Объявить о входящем звонке ВЕЗДЕ, куда не дотягивается сам тост, — и одной
 * ручкой всё это погасить. Зовёт это ровно одно место, `IncomingToast.tsx`
 * (см. его комментарий про то, почему эффект тоста — единственный владелец):
 * второй вызов однажды уже завёлся и был удалён как дефект, потому что давал
 * два уведомления об одном звонке.
 *
 * Три сигнала, и все три — про свёрнутое окно, потому что открытое всё уже
 * показало тостом:
 *
 *  1. **Заголовок вкладки** (`flashTitle`) — единственное, что видно от
 *     свёрнутой вкладки в полосе табов. Идёт всегда: он беззвучен, живёт
 *     внутри вкладки и разрешений ни у кого не спрашивает.
 *  2. **Нативная оболочка** (`shellRingStart`) — она умеет то, чего вкладка
 *     не может вовсе: поднять окно поверх всего и написать «входящий вызов»
 *     в трее. Вне оболочки вызов молча ни к чему не приводит (мост сам знает,
 *     что он в браузере), и проверять это здесь нечем и незачем.
 *  3. **Системное окошко** — и вот его показывает РОВНО ОДИН: в оболочке —
 *     она сама (в WKWebView `Notification` API просто нет, а в WebView2 он
 *     упирается в разрешения хоста), в обычном браузере — эта вкладка.
 *     Правило «показывать ли вообще» — общее (`wantsSystemNotice`), решение
 *     «кому показывать» — здесь и только здесь. Иначе на десктопе об одном
 *     звонке приходило бы два уведомления.
 *
 * Разрешение браузера спрашиваем здесь же, а не заранее отдельной кнопкой:
 * отдельная кнопка «разрешить уведомления» без звонка, который её
 * оправдывает, — это запрос в пустоту, на который человек отвечает бездумным
 * «нет». Плата честная: первый в жизни звонок в свёрнутое окно может окошка и
 * не показать (пока браузер спрашивает, вызов успевает кончиться) — зато все
 * следующие, если разрешили, покажут сразу.
 *
 * Возвращает ручку закрытия, а не ничего: тост обязан убрать за собой ровно
 * тогда, когда убирает себя (принят, отклонён, отбой, не ответили, обрыв
 * сокета — общий список `stores/ring.ts`), а не ждать, пока всё это истечёт
 * само. `close()` безопасен и до того, как окошко реально возникло: если
 * разрешение спрашивается асинхронно и вызов кончился раньше ответа, флаг
 * `cancelled` не даёт показать окошко о вызове, которого уже нет.
 */
export function notifyCall(from: CallPerson, video: boolean): CallNotification {
  const flash = flashTitle(tx('call.title.incoming', { nick: from.nick }));
  const notice = wantsSystemNotice();
  shellRingStart({ nick: from.nick, video, notify: notice });

  let cancelled = false;
  let shown: Notification | null = null;
  const close = () => {
    cancelled = true;
    flash.stop();
    shellRingStop();
    shown?.close();
  };

  // Окошко берёт на себя оболочка (см. пункт 3 выше) либо показывать его
  // нечем/незачем — остальные два сигнала уже ушли.
  if (!notice || inShell() || typeof Notification === 'undefined') return { close };

  const show = () => {
    if (cancelled) return;
    shown = new Notification(from.nick, {
      body: tx(video ? 'call.videoCall' : 'call.incoming.ringing'),
      tag: 'relay-call',
    });
    // Клик по системному окошку возвращает к вкладке, где и лежит тост с
    // настоящими «принять»/«отклонить» — окошко само эти кнопки не несёт.
    shown.onclick = () => {
      window.focus();
      shown?.close();
    };
  };

  if (Notification.permission === 'granted') {
    show();
  } else if (Notification.permission === 'default') {
    void Notification.requestPermission().then((permission) => {
      if (permission === 'granted') show();
    });
  }

  return { close };
}
