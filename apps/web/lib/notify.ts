'use client';

import { getSfx } from '@/lib/sfx';
import { isChannelLoud, useNotifyStore } from '@/stores/notify';

/**
 * Уведомление о входящем сообщении — одна точка входа на оба сигнала.
 *
 * Вспышка в сайдбаре идёт всегда и на каждое сообщение: она беззвучна и стоит
 * одного мигания точки. Звук — только там, где его разрешили (stores/notify, по
 * умолчанию молчат все); общий мут и выбор устройства вывода уже держит lib/sfx,
 * так что наушники в панели голоса глушат и этот тик тоже.
 *
 * Пауза между тиками — чтобы живая переписка не превращалась в очередь.
 * Разговор на пять реплик подряд стоит одного сигнала: он сообщает «в канале
 * что-то происходит», а не считает сообщения. Сервер уже склеивает свои пинги
 * активности (chat-activity, 80 мс) — этого мало для человеческого темпа речи.
 * Вспышку пауза не касается: считать реплики глазами не мешает никому.
 */
const COOLDOWN_MS = 1500;

// −∞, а не 0: первый за сеанс тик паузой не связан.
let lastAt = -Infinity;

export function notifyMessage(slug: string) {
  if (!slug) return;
  const s = useNotifyStore.getState();
  s.notePing(slug);
  if (!isChannelLoud(s, slug)) return;
  const now = Date.now();
  if (now - lastAt < COOLDOWN_MS) return;
  lastAt = now;
  getSfx().play('message');
}

/**
 * Тебя назвали — звук идёт мимо настройки канала и мимо паузы.
 *
 * Звук канала — это про «там что-то происходит», и молчание по умолчанию тут
 * правильно: чужой разговор не обязан тебя дёргать. Обращение по имени —
 * другое дело: его адресовали лично, и промолчать о нём потому, что канал
 * заглушён, значит заглушить не канал, а человека. Общий мут (наушники в
 * панели голоса) при этом по-прежнему главнее — его держит lib/sfx.
 *
 * Паузу между тиками мы всё же двигаем: назвали и тут же написали пять реплик
 * — вызов уже прозвучал, догонять его чередой сигналов незачем.
 */
export function notifyMention(slug: string) {
  if (!slug) return;
  useNotifyStore.getState().notePing(slug);
  lastAt = Date.now();
  getSfx().play('message');
}

/**
 * Тик в ответ на включение звука канала. Настройка, которую нельзя проверить,
 * не проверяется никогда: ждать чужого сообщения, чтобы узнать, не выкручена ли
 * система на ноль, — плохая сделка. Мимо канала и паузы: это не уведомление.
 */
export function previewMessageSound() {
  getSfx().play('message');
}
