import { encode } from 'uqr';

/**
 * QR как один путь SVG.
 *
 * Рисуем сами, а не готовой картинкой из библиотеки, по двум причинам: цвет
 * берётся из темы (в тёмной теме чёрный квадрат на белом — это фонарь в лицо),
 * и один `<path>` вместо тысячи `<rect>` не роняет перерисовку диалога.
 *
 * Кодировать вручную не стали намеренно: Рид-Соломон, маски и выбор версии —
 * это не «немного математики», а место, где ошибка выглядит как «у половины
 * телефонов не читается», и ловится она только чужой камерой.
 */

export interface QrPath {
  /** Сторона матрицы в модулях, вместе с полями. Это и есть viewBox. */
  size: number;
  /** Путь из квадратов-модулей: `fill-rule` тут не нужен, они не пересекаются. */
  path: string;
}

export function qrPath(text: string): QrPath {
  // Поля в четыре модуля — требование стандарта, без них сканеры не находят
  // код на пёстром фоне. Уровень коррекции M: код живёт на экране, а не на
  // мятой наклейке, но пальцем его закрывают регулярно.
  const qr = encode(text, { border: 4, ecc: 'M' });
  const parts: string[] = [];
  for (let y = 0; y < qr.size; y += 1) {
    let run = 0;
    for (let x = 0; x <= qr.size; x += 1) {
      // Соседние модули строки сливаются в один прямоугольник: путь короче в
      // разы, а картинка та же.
      if (x < qr.size && qr.data[y][x]) {
        run += 1;
        continue;
      }
      if (run) parts.push(`M${x - run} ${y}h${run}v1h-${run}z`);
      run = 0;
    }
  }
  return { size: qr.size, path: parts.join('') };
}
