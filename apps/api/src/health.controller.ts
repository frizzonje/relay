import { Controller, Get } from '@nestjs/common';

/**
 * Публичный health: только «жив ли процесс». Ни версии, ни данных об
 * инсталляции — наружу смотрят и docker healthcheck, и внешний мониторинг,
 * и посторонний (план 1.0, слой 4: «без версии — незачем раздавать номер
 * сборки всем подряд»).
 *
 * Зависший цикл событий — ровно то, что `restart: unless-stopped` не ловит:
 * процесс жив, но не отвечает, а перезапуск смотрит только на выход процесса.
 * Обычного 200 достаточно, чтобы такое зависание стало ВИДНЫМ — healthcheck в
 * compose пометит контейнер unhealthy, и это увидит `docker ps` и внешний
 * мониторинг. Перезапускать повисшее сам compose не умеет: лечение — за
 * оркестратором или автохилом (audit S7).
 */
@Controller('api')
export class HealthController {
  @Get('health')
  health(): { ok: true } {
    return { ok: true };
  }
}
