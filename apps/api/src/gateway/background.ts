/**
 * Работа, начатая гейтвеем и никем не ожидаемая.
 *
 * Такая работа у нас есть намеренно. Отметку о пропущенном звонке пишет лента,
 * а оба конца ждут «чем кончилось» прямо сейчас: заставить их дождаться записи
 * в базу значило бы держать человека на экране дозвона ради строки в переписке.
 * То же и с узнаванием личности на подключении, и с личными настройками —
 * первый кадр приложения не должен ждать похода в базу.
 *
 * Но «никто не ждёт» и «дождаться нельзя» — разные вещи, и разница у них
 * дорогая. Сервис останавливают сигналом, и начатая вставка обязана доехать до
 * базы прежде, чем закроется соединение с ней: иначе пропущенный звонок,
 * случившийся за секунду до рестарта, пропадает бесследно. А на стенде тестов
 * та же брошенная вставка встречалась с TRUNCATE следующего теста — и Postgres
 * разнимал их взаимной блокировкой, роняя релиз (release-images #18 на теге
 * v2.0.0).
 *
 * Отсюда правило: начатую работу регистрируем, а тот, кому нужна тишина
 * (остановка сервиса, очистка базы на стенде), спрашивает `settled()`.
 */
export class BackgroundWork {
  /** Уже обёрнутые обещания: они не отклоняются, ошибку снимает `run`. */
  private readonly pending = new Set<Promise<void>>();

  /**
   * Куда сказать об упавшей работе. Молчать нельзя: упавшая запись — это
   * потерянная отметка, а не потерянный процесс, и заметить её больше негде.
   */
  constructor(private readonly onFailure: (what: string, err: unknown) => void) {}

  /** Начатая работа. `what` — то, что скажут, если она не доедет. */
  run(what: string, work: Promise<unknown>): void {
    const tracked = work
      .then(
        () => undefined,
        (err: unknown) => this.onFailure(what, err),
      )
      .finally(() => {
        this.pending.delete(tracked);
      });
    this.pending.add(tracked);
  }

  /**
   * Дождаться тишины.
   *
   * Циклом, а не одним `Promise.all`: работа умеет начинать работу (запись
   * отметки открывает беседу, и только потом пишет строку), и снимок очереди,
   * взятый один раз, разошёлся бы ровно на этом продолжении.
   */
  async settled(): Promise<void> {
    while (this.pending.size) await Promise.all([...this.pending]);
  }
}
