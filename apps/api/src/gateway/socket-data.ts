import type { DefaultEventsMap, Server, Socket } from 'socket.io';
import type { Speaker } from '../identity/identity.service';

/** Ведро токенов лимитера: сколько осталось и когда его считали. */
export interface TokenBucket {
  tokens: number;
  ts: number;
}

/**
 * Всё, что сервер помнит про сокет между его сообщениями.
 *
 * До этого объявления `client.data` был нетипизированным мешком: каждое чтение
 * писалось как `client.data.room as string | undefined`, а опечатка в имени
 * поля молча заводила новое. Здесь ровно те же восемнадцать полей — ни одного
 * нового, ни одного переименованного, — но теперь их список можно прочесть
 * целиком, и это же список того, что дальше делится по владельцам.
 *
 * Поля сгруппированы по будущим хозяевам (см. docs/plans/old/core-refactor.md):
 * контур доступа, голосовая сессия, чат-сессия. Пока владельцев нет, группы —
 * только комментарии, но границы уже проведены здесь.
 *
 * Все поля необязательные, и это не небрежность: сокет живёт от подключения,
 * а не от входа в канал, — до `join` половина из них честно пуста.
 */
export interface SocketData {
  // ── Контур доступа ────────────────────────────────────────────────────────
  /** Устройство из handshake. По нему решается владение серверами и каналами. */
  clientId?: string;
  /** Личность за ключом — если сокет её предъявил (см. `afterInit`). */
  identity?: Speaker;
  /** Власть над инсталляцией. Выясняется один раз, обновляется `syncOwner`. */
  owner?: boolean;
  /** Забанен на всю инсталляцию: такому дверь не открывается вовсе. */
  banned?: boolean;
  /** Серверы, с которых сокет забанен. Обычный случай — пустое множество. */
  bannedFrom?: Set<string>;
  /** Гость по инвайту: без личности, с правами на один канал. */
  guest?: boolean;
  /** Единственный канал, куда гостю можно. */
  guestRoom?: string;
  /** Гость-слушатель: право говорить не выдано (подписано в токене). */
  guestListen?: boolean;
  /** Закрытые серверы, пароль которых этот сокет уже ввёл. */
  unlocked?: Set<string>;
  /** Бакет общего лимитера сообщений (см. `spend`). */
  rl?: TokenBucket;
  /** Бакет диагностических вех — свой, чтобы телеметрия не съедала звонок. */
  rlDiag?: TokenBucket;

  // ── Голосовая сессия ──────────────────────────────────────────────────────
  /** Голосовой канал, в котором сокет сейчас находится. */
  room?: string;
  /** Имя, под которым сокет говорит в эфире. */
  name?: string;
  /** Как сокет ведёт разговор. Называет клиент, сервер знает лишь режим канала. */
  transport?: 'p2p' | 'sfu';
  /** Микрофон открыт. `undefined` — клиент ещё не сказал (см. `media-update`). */
  micOn?: boolean;
  /** Наушники выключены (заодно глушится и микрофон). */
  deafened?: boolean;
  /** Канал, на который выдан пропуск в медиасервер. */
  sfuPassRoom?: string;

  // ── Чат-сессия ────────────────────────────────────────────────────────────
  /** Текстовый канал, чью ленту сокет читает. Отдельно от голосового. */
  chatRoom?: string;
  /** Имя, под которым сокет пишет. Отдельно от голосового — их правит `rename`. */
  chatName?: string;
}

/**
 * Сокет и сервер этого приложения. Отличаются от `Socket`/`Server` из socket.io
 * ровно одним: у их `data` есть тип. Больше псевдонимы не делают ничего — они
 * и не должны.
 */
export type AppSocket = Socket<DefaultEventsMap, DefaultEventsMap, DefaultEventsMap, SocketData>;
export type AppServer = Server<DefaultEventsMap, DefaultEventsMap, DefaultEventsMap, SocketData>;
