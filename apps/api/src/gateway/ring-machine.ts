/**
 * Машина состояний вызова — близнец `packages/shared/src/ring.ts`.
 *
 * Копия, а не общий импорт, по той же причине, что и каталог настроек (см.
 * `../settings/catalog.ts`): `@relay/shared` отдаётся исходником на ESM
 * (`main: ./src/index.ts`), а api собирается tsc в commonjs с `rootDir: ./src`
 * и уезжает в образ одним `dist` — импорт оттуда не пережил бы ни компиляцию
 * (файл вне `rootDir`), ни запуск (`require` файла `.ts`, которого в
 * `pnpm deploy --prod` вдобавок и нет). Веб при этом читает машину из самого
 * пакета: по её состояниям он рисует и экран исходящего, и тост входящего.
 *
 * Цена копии — расхождение, и здесь оно было бы худшего сорта. Чем кончился
 * дозвон, обязаны считать одинаково трое: владелец живых вызовов на сервере,
 * экран звонящего и тост собеседника. Разъедься половины — и симптом будет вида
 * «у него звонок ещё идёт, а у меня уже пропущенный», то есть ровно то, ради
 * чего разбор гонок и вынесен в чистую функцию.
 *
 * Поэтому копия сверяется не по духу, а по букве: `packages/shared/src/ring.test.ts`
 * сравнивает два файла слово в слово, начиная с первого объявления. Правка
 * машины — это правка обоих файлов, и `diff` между ними обязан показывать ровно
 * эту шапку, ничего больше.
 *
 * Ниже — текст близнеца без единого изменения.
 */

/**
 * Состояния вызова: два живых и шесть исходов.
 *
 * `idle` — вызов собран, но «позвонить» ещё не нажато; в это состояние никто не
 * возвращается. `ringing` — единственное, где события что-то значат. Остальные
 * шесть конечны и различимы намеренно: человеку на экране «отклонили»,
 * «не ответили», «занято» и «не в сети» объясняют совершенно разные вещи, и
 * свести их в один `ended` значило бы соврать всем четверым сразу.
 *
 * `failed` — это «собеседник исчез, не ответив»: устройство пропало между
 * звонком и ответом. Отказ сервера `offline` на `call-start` — другая вещь: там
 * вызова ещё нет, и до этой машины дело не доходит.
 */
export type RingState =
  | 'idle'
  | 'ringing'
  | 'accepted'
  | 'declined'
  | 'no-answer'
  | 'busy'
  | 'cancelled'
  | 'failed';

/**
 * Что может случиться с вызовом. `at` — время события по часам того, кто его
 * породил (на практике сервера): из него берётся начало дозвона и его конец, а
 * значит и длительность в отметке о пропущенном.
 *
 * `cancel` — отбой звонящего, `decline` — отказ собеседника: разные кнопки у
 * разных людей и разные исходы. `busy` и `peer-gone` кнопок не имеют вовсе —
 * их приносит сервер, узнав, что собеседник уже в разговоре или что его
 * последнее устройство отвалилось.
 */
export type RingEvent =
  | { type: 'call'; at: number }
  | { type: 'accept'; at: number }
  | { type: 'decline'; at: number }
  | { type: 'cancel'; at: number }
  | { type: 'timeout'; at: number }
  | { type: 'busy'; at: number }
  | { type: 'peer-gone'; at: number };

/**
 * Вызов целиком. `from`/`to` — личности, а не сокеты: звонят человеку, и
 * пережить обрыв одного устройства вызов обязан.
 *
 * `endedAt` ставится ровно один раз — в тот момент, когда вызов перестал
 * звонить, любым из шести способов, включая приём. Это конец ДОЗВОНА, а не
 * разговора: `endedAt - startedAt` у принятого — сколько человек тянулся к
 * кнопке, у пропущенного — сколько звонило.
 */
export interface Ring {
  id: string;
  from: string;
  to: string;
  state: RingState;
  startedAt: number;
  endedAt?: number;
}

/**
 * Чем кончается звонящий вызов — по одному исходу на событие.
 *
 * Таблица полная по построению: `Record` от всех событий, кроме `call`,
 * заставит дописать сюда строку, если событий станет больше. Молчаливой ветки
 * «неизвестное событие» тут быть не может — она и есть тот самый вызов,
 * который звонит вечно.
 */
const OUTCOME: Record<Exclude<RingEvent['type'], 'call'>, RingState> = {
  accept: 'accepted',
  decline: 'declined',
  cancel: 'cancelled',
  timeout: 'no-answer',
  busy: 'busy',
  'peer-gone': 'failed',
};

/**
 * Конечные состояния — списком, а не отрицанием «всё, кроме живых».
 *
 * Ошибиться тут можно в обе стороны, и стороны неравноценны: сказать «конечно»
 * про живой вызов — это забыть его на лету (сервер выкинет из памяти вызов,
 * который у обоих на экране звонит), а сказать «не конечно» про мёртвый — это
 * лишняя запись в памяти до следующей уборки. Поэтому ошибаемся в сторону
 * протечки: новое состояние, появившись, сюда не попадёт само (`Record` не даст
 * его забыть при сборке), а на неизвестной строке от чужого клиента `[state]`
 * даст `undefined` — то есть «живой», а не «выкидывай».
 */
const SETTLED: Record<RingState, boolean> = {
  idle: false,
  ringing: false,
  accepted: true,
  declined: true,
  'no-answer': true,
  busy: true,
  cancelled: true,
  failed: true,
};

/**
 * Исходы, оставляющие отметку в переписке.
 *
 * Только два. «Не ответили» и «не в сети» — это то, о чём собеседник не узнал:
 * ему звонили, а он не увидел, и отметка здесь единственный способ ему об этом
 * сказать. Остальные четыре человек уже видел своими глазами: «отклонён» он
 * нажал сам, «занято» случилось у него в разговоре, «принят» состоялся,
 * а «отбой» — это звонящий передумал, и метка о чужой секундной ошибке была бы
 * шумом, а не заботой.
 */
const MISSED: Record<RingState, boolean> = {
  idle: false,
  ringing: false,
  accepted: false,
  declined: false,
  'no-answer': true,
  busy: false,
  cancelled: false,
  failed: true,
};

/**
 * Переход. Возвращает ТОТ ЖЕ объект, если событие в этом состоянии не значит
 * ничего, — сравнением по ссылке (`next === ring`) владелец вызова дёшево
 * узнаёт, что рассылать нечего, и не шлёт обоим сторонам «состояние не
 * изменилось».
 *
 * Правило, которое стоит прочесть один раз и не искать потом по веткам:
 * **из конечного состояния выхода нет**. Проверка стоит первой строкой и одна
 * на все шесть исходов — поэтому «таймаут после принятия», «принять после
 * отклонения», «обрыв после ответа» и всё, что ещё придумает сеть, не значат
 * ничего по одной и той же причине, а не по шести разным.
 *
 * Отсюда же разбирается гонка «отбой и принятие в одну миллисекунду»:
 * побеждает не меньший `at`, а тот, кто первым дошёл до владельца вызова, —
 * второе событие приходит уже в конечное состояние и гаснет. Выбор
 * сознательный: правило «принятие важнее отбоя» потребовало бы придержать
 * решённый вызов в ожидании возможного лучшего события, то есть ровно того
 * подвешенного состояния, ради борьбы с которым эта машина и написана. К тому
 * же нажавший «отбой» не должен оказаться в разговоре, из которого он только
 * что вышел, а проигравшему «принять» видно ровно то же, что при отбое
 * миллисекундой раньше, — вызов исчез, и объяснять тут нечего.
 */
export function step(ring: Ring, event: RingEvent): Ring {
  if (settled(ring.state)) return ring;

  // Звонок заводит часы дозвона. По идущему вызову он не значит ничего: иначе
  // второй `call-start` сдвинул бы `startedAt`, а вместе с ним и таймаут.
  if (event.type === 'call') {
    return ring.state === 'idle' ? { ...ring, state: 'ringing', startedAt: event.at } : ring;
  }

  // Остаётся `idle`: у собеседника ещё не звонит, отвечать не на что.
  if (ring.state !== 'ringing') return ring;

  return { ...ring, state: OUTCOME[event.type], endedAt: event.at };
}

/** Конечное ли состояние: по нему решают, убирать ли вызов из памяти. */
export function settled(state: RingState): boolean {
  return SETTLED[state] === true;
}

/** Пропущенный ли это исход — то, что рисуется отметкой в переписке. */
export function missed(state: RingState): boolean {
  return MISSED[state] === true;
}
