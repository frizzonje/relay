/**
 * Ведро токенов — один расчёт на все лимитеры api.
 *
 * Лимитеров два, и списывают они разное: сокет платит токеном за сообщение,
 * загрузка — байтами записанного файла. Общее у них — только ведро: оно полно
 * при первой встрече, наполняется с постоянной скоростью и не переливается
 * через край. Это и живёт здесь; что и когда списывать, решает владелец.
 */

/** Сколько осталось и когда считали. Хранит владелец — на сокете, в карте. */
export interface TokenBucket {
  tokens: number;
  ts: number;
}

/**
 * Ведро на момент `now`: долитое за прошедшее время, не выше `capacity`.
 * Нет ведра — значит, впервые: начинаем с полного. Ведро меняется на месте и
 * возвращается — владелец сохраняет его у себя, если его ещё там нет.
 */
export function refill(
  bucket: TokenBucket | undefined,
  capacity: number,
  perSec: number,
  now: number,
): TokenBucket {
  const b = bucket ?? { tokens: capacity, ts: now };
  b.tokens = Math.min(capacity, b.tokens + ((now - b.ts) / 1000) * perSec);
  b.ts = now;
  return b;
}
