/**
 * Версия сервера — та, под которой собран образ.
 *
 * Приезжает build-arg'ом из тега релиза и дальше живёт в окружении. Пустая
 * строка — это не сбой, а честный ответ инсталляции, собранной из исходников
 * (`docker compose build`): у неё номера релиза нет и придумывать его нельзя.
 * Выдуманный номер хуже отсутствующего — по нему станут сверять поведение.
 */
export function serverVersion(): string {
  return (process.env.RELAY_VERSION ?? '').trim();
}
