import { createHmac, randomBytes } from 'crypto';

/**
 * Учётные данные для TURN — временные и на каждого свои.
 *
 * Долгоживущая пара «webrtc:пароль», одна на всю инсталляцию, выдаётся каждому
 * вошедшему открытым текстом первым же `/api/config`. Отозвать её нельзя иначе
 * как правкой `.env` с рестартом, то есть оборвав звонки всем разом, а до тех
 * пор любой, кто зашёл однажды, ретранслирует через сервер что угодно и сколько
 * угодно — уже не будучи пользователем relay.
 *
 * Вместо этого coturn поднимается с `--use-auth-secret`: он не хранит список
 * пользователей, а проверяет подпись. Логин — это срок годности, пароль —
 * HMAC-SHA1 от логина на общем секрете (draft-uberti-behave-turn-rest-00, он же
 * «TURN REST API»). Секрет остаётся на сервере и не покидает его никогда, а
 * выданное перестаёт работать само.
 *
 * Переключатель один — `TURN_SECRET`, и он же признак режима у обеих сторон:
 * api выдаёт подписанное, `infra/coturn-entrypoint.sh` поднимает сервер под ту
 * же проверку. Читают они одну переменную из одного `.env`, поэтому разойтись
 * не могут. Не задана — всё работает по-старому (см. `config.controller.ts`):
 * инсталляция, у которой TURN_URLS смотрит на чужого провайдера со статической
 * парой, не должна сломаться оттого, что мы улучшили свой ретранслятор.
 */

/** Секрет, общий у api и coturn. Клиенту не показывается ни в каком виде. */
export function turnSecret(): string {
  return process.env.TURN_SECRET || '';
}

/**
 * Срок жизни выданной пары. Сутки — не осторожность, а мера устаревания:
 * конфиг запрашивается один раз на загрузку страницы, и вкладка, оставленная
 * открытой на ночь, обязана дозвониться утром. Короче делать нечего —
 * украденная пара даёт ретрансляцию, а не доступ к данным, и умирает сама.
 */
export function turnTtlSeconds(): number {
  const raw = Number(process.env.TURN_TTL_SECONDS);
  if (!Number.isFinite(raw) || raw <= 0) return 24 * 60 * 60;
  // Ниже минуты осмысленного значения не бывает: столько живёт сама попытка
  // соединиться. Выше недели держать подпись незачем — это уже «навсегда»,
  // ради ухода от которого всё и затевалось.
  return Math.min(Math.max(Math.floor(raw), 60), 7 * 24 * 60 * 60);
}

export interface TurnCredentials {
  username: string;
  credential: string;
  /** Unix-время в секундах, когда пара перестанет работать. */
  expiresAt: number;
}

/**
 * Логин — `<когда истечёт>:<кто>`, где «кто» — случайная метка этой выдачи.
 * Личности здесь взяться неоткуда: по http инсталляция знает только «пропуск
 * есть», ключ живёт на сокете. Но метка всё равно не лишняя — в логе coturn по
 * ней видно, что ретрансляции идут от разных сессий, а не от одной, и какая
 * именно пара выбрала полосу.
 */
export function issueTurnCredentials(secret: string, now = Date.now()): TurnCredentials {
  const expiresAt = Math.floor(now / 1000) + turnTtlSeconds();
  const username = `${expiresAt}:${randomBytes(4).toString('hex')}`;
  return { username, credential: signTurnUsername(secret, username), expiresAt };
}

/**
 * SHA-1 здесь не выбор, а протокол: coturn считает именно её и сверяет байты.
 * Ключ — секрет, сообщение — логин целиком, ответ — base64 (не base64url).
 */
export function signTurnUsername(secret: string, username: string): string {
  return createHmac('sha1', secret).update(username).digest('base64');
}
