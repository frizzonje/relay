/**
 * Экранирование для `LIKE`/`ILIKE` (с `ESCAPE '\'`). Без него ник «100%»
 * находил бы всех подряд, а подчёркивание в поиске означало бы «любой знак» —
 * то есть поиск врал бы тем тише, чем реже им пользуются.
 */
export function escapeLike(text: string): string {
  return text.replace(/[\\%_]/g, (ch) => `\\${ch}`);
}
