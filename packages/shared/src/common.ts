/** Общее: имя приложения, версия протокола, пределы полей и человек так, как его показывают. */

/**
 * Единый контракт фронт↔бэк relay.
 *
 * Источник правды для socket-событий, REST DTO, типов вложений/ICE и общих
 * констант. Импортируется и web (Next), и api (Nest). Намеренно не зависит от
 * lib.dom: вместо RTCSessionDescriptionInit/RTCIceCandidateInit используем
 * структурно-совместимые типы, чтобы пакет компилировался и на стороне Node.
 */

export const APP_NAME = 'relay';

/**
 * Форма тела из контракта — без доверия к значениям. Так серверы (api, sfu)
 * описывают то, что прислал клиент: какие поля бывают, известно отсюда, а
 * что в них лежит, решает разбор, — тело события socket.io не проверяет никто.
 */
export type Untrusted<T> = { [K in keyof T]?: unknown };

/**
 * Версия контракта сигналинга — единственное, что клиент обязан сказать о себе
 * на рукопожатии.
 *
 * Нужна она ради одного ответа: «обнови приложение» вместо белого экрана. До
 * 1.0 версии не было вовсе, и клиент, отставший от сервера, вёл себя как
 * сломанный — молчащие каналы, отбитые входы, вечное «переподключаюсь», — а
 * человек читал это как поломку relay. Теперь сервер такому отказывает во
 * входе и говорит, чего именно не хватает.
 *
 * Поднимается вместе с мажором и только с ним: каждый подъём — это отказ во
 * входе всем, кто не обновился, то есть решение, а не деталь реализации.
 */
export const PROTOCOL_VERSION = 1;

/** Серверные ограничения на длину полей (усечение на бэке). */
export const LIMITS = {
  /** Слаг комнаты (голосовой/текстовой). */
  room: 32,
  /** Отображаемое имя участника. */
  name: 20,
  /** Длина текста сообщения. */
  chatText: 500,
} as const;

/**
 * Человек так, как его показывают и адресуют: лицо и адрес — отпечаток ключа,
 * подпись — ник. Ники свободные и не уникальные, поэтому сверяют всегда по
 * отпечатку, а ник лишь подписывает — каким он был в тот момент.
 */
export interface Person {
  fingerprint: string;
  nick: string;
}

/**
 * Человек, у которого ключа может не быть: гость по инвайту (ключа ему не
 * выдавали) или запись, сделанная до 1.0. Лицом такому остаётся градиент по
 * имени.
 */
export type PersonOrGuest = Pick<Person, 'nick'> & Partial<Pick<Person, 'fingerprint'>>;
