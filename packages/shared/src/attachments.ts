/**
 * Вложения: что приезжает с сообщением файлом и сколько он может весить.
 * Отдельным файлом, потому что их знают и чат, и каталог настроек (какие
 * виды вложений инсталляция пускает), а каталогу незачем тянуть весь контракт.
 */

/** Лимит размера загружаемого файла — 25 МБ. */
export const MAX_UPLOAD_BYTES = 25 * 1024 * 1024;

/** Как клиент рисует вложение: картинка инлайн, mp3 — плеером, прочее — карточкой. */
export type AttachmentKind = 'image' | 'audio' | 'file';

export interface Attachment {
  url: string;
  name: string;
  size: number;
  mime: string;
  kind: AttachmentKind;
  /** Спойлер: клиент рисует вложение заблюренным до клика («показать»). */
  spoiler?: boolean;
}
