import type { AuditCursor, AuditEntry, BanEntry, SettingsSnapshot } from './index';
import type { SettingGroup, SettingSpec, SettingValue } from './settings';

/**
 * Протокол админ-панели: что панель спрашивает у сервера и что получает в ответ.
 *
 * Половина контракта для клиента; вторая половина — валидаторы сервера в
 * `apps/api/src/gateway/protocol.ts`. api намеренно не зависит от этого пакета
 * (см. шапку `settings.ts`), поэтому совпадение половин держит тест
 * (`index.test.ts`), а не общий импорт.
 *
 * Главное правило панели живёт не здесь, а в каждом обработчике сервера, и
 * повторить его стоит: ПАНЕЛЬ ТОЛЬКО ДЛЯ ВЛАДЕЛЬЦА, и владение проверяет
 * каждое событие само. Отсутствие кнопки на экране проверкой не считается —
 * события socket.io шлёт кто угодно.
 *
 * Все события панели с ack. Панель — не лента: человек нажал и обязан узнать,
 * приняли его правку или отвергли и почему; молчаливый отказ здесь означал бы
 * «поле в панели ничего не делает», то есть худший вид вранья.
 */

/**
 * Действие панели — то, что делают кнопкой, а не полем.
 *
 * Отдельно от параметров, потому что у действия нет значения: его нельзя
 * «поставить в true», его совершают. Список закрыт: незнакомое имя сервер
 * отвергает (`unsupported`), а не пытается угадать.
 */
export type AdminAction =
  /** Перевыпустить ссылку владельца. Прежняя невостребованная умирает. */
  | 'owner-link'
  /** Прогнать ретенцию прямо сейчас, не дожидаясь часового таймера. */
  | 'retention-run'
  /** Подмести осиротевшие вложения. */
  | 'files-sweep'
  /** Отозвать все выданные сессии — включая свою. */
  | 'revoke-sessions'
  /** Отозвать одно устройство (`target` — его id). */
  | 'revoke-device'
  /** Забанить на всю инсталляцию (`target` — отпечаток). */
  | 'ban'
  /** Снять бан на инсталляцию (`target` — отпечаток). */
  | 'unban'
  /** Выгрузить настройки — без секретов. */
  | 'export'
  /** Загрузить настройки из выгрузки: годное применить, отвергнутое назвать. */
  | 'import';

/**
 * Почему панели отказали.
 *
 * Шесть причин посередине — это причины каталога (`SettingError`): «не то
 * значение» и «слишком длинное» человек чинит по-разному, и общий отказ
 * советовал бы ему невозможное. Остальные — про саму панель.
 *
 * Список общий на все её события намеренно: панель показывает отказ одним и
 * тем же способом, и второй перечень причин разошёлся бы с первым.
 */
export type AdminRefusal =
  /** Не владелец. Единственный ответ всякому, кто не он, — на любом событии. */
  | 'forbidden'
  /** Опасное просит подтверждения, и его не прислали. */
  | 'needs-confirm'
  | 'unknown-key'
  | 'read-only'
  | 'wrong-type'
  | 'out-of-range'
  | 'not-an-option'
  | 'too-long'
  /** Пункт списка не той формы: строка, которая адресом с маской не является. */
  | 'bad-item'
  /** Секрет общей дорогой не пишется — у пароля инсталляции своя. */
  | 'secret-path'
  /** Цели действия нет: такого отпечатка, устройства или бана не существует. */
  | 'not-found'
  /** Такого действия сервер не знает — клиент новее сервера. */
  | 'unsupported';

/**
 * Сводка: то, что владелец видит первым, открыв панель.
 *
 * Считается запросами в момент вопроса, а не счётчиками в памяти: счётчик
 * переживает рестарт враньём, а число, посчитанное по таблице, — единственное,
 * которое сходится с тем, что человек увидит на вкладке рядом.
 */
export interface AdminOverview {
  /** Личностей всего. */
  people: number;
  /** Сколько их на связи прямо сейчас. Одна личность с двух устройств — одна. */
  online: number;
  /** Банов на всю инсталляцию (не на отдельные серверы). */
  bans: number;
  /** Реплик в базе — вместе с личной перепиской. */
  messages: number;
  servers: number;
  channels: number;
  /** Сколько занято вложениями. */
  storageBytes: number;
  /** Квота каталога загрузок; 0 — без квоты. */
  storageQuotaBytes: number;
  /** Действующая политика хранения — та, по которой чистят каналы. */
  retention: AdminRetention;
  /** Своя политика личной переписки или `null`, если она общая с каналами. */
  directRetention: AdminRetention | null;
  /** Версия сервера. Пусто — образ собран из исходников, номера у него нет. */
  version: string;
}

/** Политика хранения так, как её показывает сводка. */
export interface AdminRetention {
  mode: 'days' | 'forever' | 'ephemeral';
  /** Только у `days`. */
  days?: number;
}

/** Устройство человека — так, как его видит владелец в таблице людей. */
export interface AdminDevice {
  id: string;
  name: string;
  /** Когда его видели в последний раз, миллисекундами. `null` — ни разу. */
  lastSeenAt: number | null;
  /** Отозвано: ключ ещё связан с личностью, но входить им уже нельзя. */
  revoked: boolean;
}

/**
 * Человек в таблице людей.
 *
 * Лицо рисуется из отпечатка (identicon) — отдельной картинки для этого нет и
 * не нужно. Id личности наружу не уходит вовсе: в протоколе человека называет
 * отпечаток, и он же служит ручкой для бана.
 */
export interface AdminPerson {
  fingerprint: string;
  nick: string;
  /** Когда завелась личность, миллисекундами. */
  createdAt: number;
  lastSeenAt: number | null;
  devices: AdminDevice[];
  /** Забанен на всю инсталляцию. */
  banned: boolean;
  /** Владелец инсталляции. Его не банят — сервер откажет. */
  owner: boolean;
}

/**
 * Выгрузка настроек. Секретов в ней нет вовсе — ни значением, ни признаком:
 * файл ездит по почте и лежит в чужих каталогах, и «пароль задан» ему сообщать
 * незачем.
 */
export interface AdminExport {
  /** Версия контракта, которой снята выгрузка. */
  protocol: number;
  /** Когда сняли, миллисекундами. */
  at: number;
  /** Значения по ключам каталога. */
  values: SettingsSnapshot;
}

/** Ключ, которого импорт не принял, и причина — из каталога. */
export interface AdminImportRejection {
  key: string;
  reason: AdminRefusal;
}

// ── Что панель присылает ────────────────────────────────────────────────────

export interface AdminSetPayload {
  key: string;
  value: unknown;
  /**
   * Подтверждение опасного (`danger` в каталоге). Поле в запросе, а не доверие
   * к тому, что панель показала диалог: диалог рисует клиент, а отвечать за
   * последствия сервер.
   */
  confirm?: boolean;
}

export interface AdminResetPayload {
  group: SettingGroup;
  /** Сброс группы подтверждают всегда — это правка десятка полей одним нажатием. */
  confirm?: boolean;
}

export interface AdminPeoplePayload {
  /** Часть ника или отпечатка. Пусто — просто список. */
  query?: string;
  /** Курсор следующей страницы — тот, что пришёл в прошлом ответе. */
  cursor?: string;
}

export interface AdminAuditPayload {
  cursor?: AuditCursor;
}

/**
 * Смена пароля инсталляции.
 *
 * Своё событие, а не поле в `admin-set` и не действие в общем ряду: пароль —
 * единственный параметр, который одновременно секрет, хранится хэшем и отзывает
 * всё выданное. Общая запись ему отказывает (`secret-path`), и это не досадное
 * ограничение, а разделение дорог.
 *
 * Пустая строка — снять пароль, заданный из панели. Инсталляция при этом не
 * обязательно открывается: под ним может лежать `SITE_PASSWORD` из окружения, и
 * она возвращается к нему.
 */
export interface AdminPasswordPayload {
  password: string;
  /** Подтверждение обязательно: сменой пароля запирают снаружи всех, включая себя. */
  confirm?: boolean;
}

export interface AdminActionPayload {
  action: AdminAction;
  /** Отпечаток (бан) или id устройства (отзыв) — смотря по действию. */
  target?: string;
  /** Подтверждение. Требуется всем действиям, кроме выгрузки. */
  confirm?: boolean;
  /** Настройки для импорта — то, что лежало в выгруженном файле. */
  values?: Record<string, unknown>;
}

// ── Что сервер отвечает ─────────────────────────────────────────────────────

/**
 * Состояние панели одним ответом: каталог, значения и сводка.
 *
 * Каталог уезжает с сервера, хотя такой же лежит и в самом клиенте. Это не
 * лишний трафик, а единственный способ не соврать: версия контракта поднимается
 * с мажором, а параметры добавляются в любом выпуске, — и панель, нарисованная
 * по своей копии, показала бы поля, которых сервер не знает, либо промолчала бы
 * о тех, которые он ждёт.
 *
 * Значения — снимок `public()`: всё, кроме значений секретов (у секрета уезжает
 * признак «задано»).
 */
export type AdminStateResult =
  | {
      ok: true;
      catalog: SettingSpec[];
      values: SettingsSnapshot;
      overview: AdminOverview;
    }
  | { ok: false; error: AdminRefusal };

/**
 * Итог записи. `changed: false` — значение уже было таким; это не отказ, и
 * панель по нему ничего не перерисовывает.
 */
export type AdminSetResult =
  | { ok: true; key: string; changed: boolean; value: SettingValue }
  | { ok: false; error: AdminRefusal };

/** Итог сброса группы: что действительно поменялось и чем стало. */
export type AdminResetResult =
  | { ok: true; group: SettingGroup; changed: string[]; values: SettingsSnapshot }
  | { ok: false; error: AdminRefusal };

/** Страница людей. `cursor` есть, только если ниже что-то ещё осталось. */
export type AdminPeopleResult =
  | { ok: true; people: AdminPerson[]; cursor?: string }
  | { ok: false; error: AdminRefusal };

export type AdminBansResult = { ok: true; bans: BanEntry[] } | { ok: false; error: AdminRefusal };

export type AdminAuditResult =
  | { ok: true; entries: AuditEntry[]; more: boolean }
  | { ok: false; error: AdminRefusal };

/**
 * Итог действия. Поля необязательные и заполняются по одному на действие:
 * ключ владельца, выгрузка, отчёт импорта, число сделанного.
 */
export type AdminActionResult =
  | {
      ok: true;
      action: AdminAction;
      /**
       * Ключ владельца — единственный раз, когда он существует в читаемом виде:
       * в базе лежит только его хэш, и второй раз этот же ключ не покажет никто.
       */
      link?: { token: string; expiresAt: number };
      settings?: AdminExport;
      imported?: { applied: string[]; rejected: AdminImportRejection[] };
      /** Сколько сделано: реплик удалено, файлов подметено, сокетов отключено. */
      count?: number;
    }
  | { ok: false; error: AdminRefusal };

/**
 * Итог смены пароля.
 *
 * `set` — заперта ли инсталляция теперь; по нему панель и рисует «пароль
 * задан», не спрашивая ничего больше. Значение пароля не уезжает обратно ни в
 * каком виде, и это не вежливость: показать его было бы нечем — сервер знает
 * только хэш.
 *
 * `changed: false` — ничего не поменялось (сняли пароль там, где его и не
 * было). `count` — сколько живых сокетов оборвано; сокет нажавшего в их числе
 * не бывает, иначе ответ было бы некому доставить.
 */
export type AdminPasswordResult =
  | { ok: true; set: boolean; changed: boolean; count: number }
  | { ok: false; error: AdminRefusal };

/**
 * Настройку поменяли из другой сессии владельца.
 *
 * Летит только его собственным сокетам, и только другим: панель, открытая на
 * втором устройстве, обязана обновиться, иначе она сохранит поверх свежей
 * правки то, что показывала минуту назад.
 *
 * Общий снимок настроек всем вкладкам рассылает событие `settings` — второй
 * такой рассылки здесь нет: `admin-changed` носит то, чего в общем снимке нет
 * вовсе (параметры без пометки `client`).
 */
export interface AdminChangedRelay {
  keys: string[];
  values: SettingsSnapshot;
}
