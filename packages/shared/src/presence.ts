/** Присутствие личности: кто на связи. */

/**
 * Где человек сейчас — на всю инсталляцию, а не в отдельном канале.
 *
 * `voice-presence` отвечает на другой вопрос — «кто в этой комнате», — и для
 * дозвона он бесполезен: звонят человеку, а не комнате. `recent` — «только что
 * был»: закрыл вкладку, потерял сеть, вышел на минуту; `offline` в снимке не
 * встречается вовсе (нет записи — нет и человека) и приходит только дельтой,
 * которой у собеседника гаснет точка.
 */
export type PresenceState = 'online' | 'in-voice' | 'recent' | 'offline';

export interface PresenceEntry {
  /** Кто: отпечаток ключа — им человек назван всюду, где он адресат. */
  fingerprint: string;
  state: PresenceState;
  /** Когда это состояние началось, мс Unix. */
  since: number;
}
